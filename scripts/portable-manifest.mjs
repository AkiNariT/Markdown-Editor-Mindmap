import { lstat, readdir } from 'node:fs/promises';
import { createReadStream } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';

export async function collectRuntimeFiles(root, { hashes = false } = {}) {
  const files = [];
  async function visit(directory, relative = '') {
    const entries = await readdir(directory, { withFileTypes: true });
    for (const entry of entries) {
      const file = path.join(directory, entry.name);
      const next = relative ? `${relative}/${entry.name}` : entry.name;
      const info = await lstat(file);
      if (info.isSymbolicLink()) throw new Error(`Runtime contains a symbolic link or junction: ${next}`);
      if (info.isDirectory()) await visit(file, next);
      else if (info.isFile()) {
        const item = { relative: next, size: info.size };
        if (hashes) {
          const digest = createHash('sha256');
          for await (const chunk of createReadStream(file)) digest.update(chunk);
          item.sha256 = digest.digest('hex');
        }
        files.push(item);
      }
      else throw new Error(`Unsupported runtime file: ${next}`);
    }
  }
  const info = await lstat(root);
  if (info.isSymbolicLink()) throw new Error('Runtime root cannot be a symbolic link or junction.');
  if (!info.isDirectory()) throw new Error('Runtime root must be a directory.');
  await visit(root);
  return files.sort((a, b) => a.relative < b.relative ? -1 : a.relative > b.relative ? 1 : 0);
}

// Embed expected sizes in the launcher, never in an editable cache manifest.
// Metadata checks detect absent/truncated files without rereading the complete
// Chromium runtime on every launch. They are not cryptographic integrity checks.
export function runtimeFileChecks(files) {
  if (!Array.isArray(files) || !files.length) throw new Error('Runtime file manifest is empty.');
  const checks = files.map(({ relative, size }) => {
    if (typeof relative !== 'string' || !relative || /[\\\x00-\x1f\x7f"<>|?*:]/.test(relative)
      || relative.split('/').some(part => !part || part === '.' || part === '..') || ['.complete', '.invalid'].includes(relative)) {
      throw new Error(`Unsafe runtime path: ${relative}`);
    }
    if (!Number.isInteger(size) || size < 0 || size > 0x7fffffff) throw new Error(`Unsupported runtime file size: ${relative}`);
    const literal = relative.replaceAll('/', '\\').replaceAll('$', () => '$$');
    return `  !insertmacro MDCheckRuntimeFile "${literal}" ${size}`;
  });
  return '; Generated by scripts/package-portable.mjs.\n!macro MDCheckAllRuntimeFiles\n' + checks.join('\n') + '\n!macroend\n';
}

// These digests are checked once before publishing a newly extracted cache.
// Warm launches continue to use only the small metadata checks above.
export function runtimeHashChecks(files) {
  runtimeFileChecks(files);
  const checks = files.map(({ relative, size, sha256 }) => {
    if (typeof sha256 !== 'string' || !/^[a-f0-9]{64}$/i.test(sha256)) throw new Error(`Missing SHA-256 digest: ${relative}`);
    const literal = relative.replaceAll('/', '\\').replaceAll('$', () => '$$');
    return `  !insertmacro MDCheckRuntimeHash "${literal}" ${size} "${sha256}"`;
  });
  return '!macro MDHashAllRuntimeFiles\n' + checks.join('\n') + '\n!macroend\n';
}
