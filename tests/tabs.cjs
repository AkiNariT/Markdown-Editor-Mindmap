const { _electron: electron } = require('playwright');
const { writeFile, readFile, mkdir } = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');

(async () => {
  const testDir = path.resolve(__dirname, '../.desktop-test/tabs');
  await mkdir(testDir, { recursive: true });
  const a = path.join(testDir, '甲.md'), b = path.join(testDir, '乙.md'), skill = path.join(testDir, 'SKILL.md');
  const long = label => `# ${label}\n\n` + Array.from({ length: 90 }, (_, i) => `## 第 ${i + 1} 节\n\n${label}的第 ${i + 1} 段正文。\n\n`).join('');
  const originalA = long('甲'), originalB = long('乙');
  await writeFile(a, originalA); await writeFile(b, originalB);
  await writeFile(skill, '---\nname: tabs-test\ndescription: 测试多个文档标签。\n---\n\n' + long('技能'));
  const executablePath = process.env.MOYE_EXE || require('electron');
  const args = process.env.MOYE_EXE ? [a] : [path.resolve(__dirname, '..'), a];
  const app = await electron.launch({ executablePath, args: [...args, '--user-data-dir=' + path.join(testDir, 'profile-' + process.pid + '-' + Date.now())], timeout: 30000 });
  try {
    const page = await app.firstWindow(); page.setDefaultTimeout(8000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.waitForSelector('.tiptap h1');
    assert.equal(await page.getByRole('tab', { name: '甲.md', exact: true }).count(), 1, '当前文件必须有可见的文档标签');
    await app.evaluate(({ dialog }) => { globalThis.tabsPrompts = []; dialog.showMessageBox = async (_, options) => { globalThis.tabsPrompts.push(options.message); return { response: 2 }; }; });
    const open = async target => {
      await app.evaluate(({ dialog }, target) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [target] }); }, target);
      await page.getByRole('button', { name: '打开', exact: true }).click();
      await page.waitForFunction(name => document.querySelector('#document-name').textContent === name, path.basename(target));
    };
    await page.locator('.canvas').evaluate(canvas => canvas.scrollTo({ top: 1800, behavior: 'instant' }));
    const anchor = page.locator('.tiptap > p').nth(16);
    const aY = await anchor.evaluate(p => p.getBoundingClientRect().top);
    await open(b);
    assert.equal(await page.getByRole('tab').count(), 2, '打开文件应增加标签');
    await page.locator('.canvas').evaluate(canvas => canvas.scrollTo({ top: 950, behavior: 'instant' }));
    const bScroll = await page.locator('.canvas').evaluate(canvas => canvas.scrollTop);
    await page.getByRole('tab', { name: '甲.md', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#document-name').textContent === '甲.md');
    assert.ok(Math.abs(await anchor.evaluate(p => p.getBoundingClientRect().top) - aY) < 1.5, '重新打开甲标签必须保留原阅读位置');
    await page.getByRole('button', { name: '编辑', exact: true }).click();
    await anchor.click(); await page.keyboard.press('End'); await page.keyboard.insertText('甲的未保存内容');
    await page.waitForFunction(() => !document.querySelector('#dirty-dot').hidden);
    const modifiedY = await anchor.evaluate(p => p.getBoundingClientRect().top);
    await page.getByRole('tab', { name: '乙.md', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#document-name').textContent === '乙.md');
    assert.equal(await page.locator('.tiptap').getAttribute('contenteditable'), 'false', '每个标签有独立模式');
    assert.ok(Math.abs(await page.locator('.canvas').evaluate(canvas => canvas.scrollTop) - bScroll) < 1.5);
    assert.ok(!(await page.locator('.tiptap').textContent()).includes('甲的未保存内容'));
    await open(a);
    assert.equal(await page.getByRole('tab').count(), 2, '重复打开文件应激活原标签');
    assert.match(await page.locator('.tiptap').textContent(), /甲的未保存内容/);
    assert.equal(await page.locator('.tiptap').getAttribute('contenteditable'), 'true');
    assert.ok(Math.abs(await anchor.evaluate(p => p.getBoundingClientRect().top) - modifiedY) < 1.5);
    assert.deepEqual(await app.evaluate(() => globalThis.tabsPrompts), [], '切换或打开文档不应要求保存其他标签');
    await anchor.click(); await page.keyboard.press('Control+z');
    assert.ok(!(await page.locator('.tiptap').textContent()).includes('甲的未保存内容'), '切换后撤销历史仍属于甲');
    await page.keyboard.press('Control+y');
    assert.match(await page.locator('.tiptap').textContent(), /甲的未保存内容/);
    await open(skill);
    await page.getByRole('button', { name: '编辑', exact: true }).click();
    await page.locator('#skill-name').fill('Invalid Name');
    await page.getByRole('tab', { name: '乙.md', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#document-name').textContent === '乙.md');
    await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 0 }); });
    await page.getByRole('button', { name: '关闭 SKILL.md', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('技能名称'));
    assert.equal(await page.getByRole('tab', { name: 'SKILL.md', exact: true }).count(), 1, '无效背景字段不应关闭或丢失标签');
    assert.equal(await page.locator('#document-name').textContent(), '乙.md', '保存背景标签不应切换当前文档');
    await page.getByRole('tab', { name: 'SKILL.md', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#document-name').textContent === 'SKILL.md');
    assert.equal(await page.locator('#skill-name').inputValue(), 'Invalid Name');
    await page.locator('#skill-name').fill('saved-skill');
    await page.getByRole('tab', { name: '乙.md', exact: true }).click();
    await page.getByRole('button', { name: '关闭 SKILL.md', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('[role=tab]').length === 2);
    assert.match(await readFile(skill, 'utf8'), /saved-skill/);
    await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 2 }); });
    await page.getByRole('button', { name: '关闭 甲.md', exact: true }).click();
    assert.equal(await page.getByRole('tab', { name: '甲.md', exact: true }).count(), 1, '取消关闭保留未保存内容');
    await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 0 }); });
    await page.getByRole('button', { name: '关闭 甲.md', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('[role=tab]').length === 1);
    assert.match(await readFile(a, 'utf8'), /甲的未保存内容/, '背景保存应写入正确文件');
    assert.equal(await readFile(b, 'utf8'), originalB);
    await page.keyboard.press('Control+w');
    await page.waitForFunction(() => document.querySelector('#document-name').textContent === '未命名');
    assert.equal(await page.getByRole('tab').count(), 1, '最后一个标签关闭后提供空白文档');
    await page.getByRole('button', { name: 'SKILL 模板', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#document-name').textContent === 'SKILL.md');
    assert.equal(await page.getByRole('tab').count(), 2);
    await page.locator('#skill-name').fill('new-template');
    await page.keyboard.press('Control+Shift+Tab');
    await page.waitForFunction(() => document.querySelector('#document-name').textContent === '未命名');
    await page.keyboard.press('Control+Tab');
    await page.waitForFunction(() => document.querySelector('#document-name').textContent === 'SKILL.md');
    assert.equal(await page.locator('#skill-name').inputValue(), 'new-template');
    await open(b);
    await page.getByRole('tab', { name: 'SKILL.md', exact: true }).click();
    await app.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }); }, b);
    await page.getByRole('button', { name: '保存', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('另一个标签'));
    assert.equal(await readFile(b, 'utf8'), originalB, '另存为不应覆盖另一个打开的标签文件');
    await page.getByRole('tab', { name: '乙.md', exact: true }).click();
    await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 0 }); dialog.showSaveDialog = async () => ({ canceled: true }); });
    await page.getByRole('button', { name: '关闭 SKILL.md', exact: true }).click();
    assert.equal(await page.getByRole('tab', { name: 'SKILL.md', exact: true }).count(), 1, '取消另存应保留后台新模板');
    await page.getByRole('tab', { name: '未命名', exact: true }).click();
    await page.locator('.tiptap').click(); await page.keyboard.insertText('空白标签的未保存内容');
    await page.getByRole('tab', { name: '乙.md', exact: true }).click();
    await page.getByRole('button', { name: '编辑', exact: true }).click();
    await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => { await new Promise(resolve => setTimeout(resolve, 300)); return { response: 2 }; }; });
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close());
    await page.waitForFunction(() => document.querySelector('.tiptap').getAttribute('contenteditable') === 'false');
    await page.waitForTimeout(200); assert.equal(page.isClosed(), false, '窗口关闭也要保护后台未保存标签');
    await page.waitForFunction(() => document.querySelector('.tiptap').getAttribute('contenteditable') === 'true');
    const savedBackground = path.join(testDir, '后台保存.md');
    await app.evaluate(({ dialog }, target) => {
      dialog.showMessageBox = async (_, options) => ({ response: options.message.includes('未命名') ? 0 : 2 });
      dialog.showSaveDialog = async () => ({ canceled: false, filePath: target });
    }, savedBackground);
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close());
    await page.waitForFunction(() => [...document.querySelectorAll('[role=tab]')].some(button => button.getAttribute('aria-label') === '后台保存.md'));
    assert.equal(page.isClosed(), false, '稍后的标签取消退出应保留窗口');
    assert.match(await readFile(savedBackground, 'utf8'), /空白标签的未保存内容/);
    assert.equal(await page.locator('#document-name').textContent(), '乙.md', '后台保存不得替换当前阅读标签');
    const stressPaths = [];
    for (let index = 0; index < 5; index++) {
      const folder = path.join(testDir, '标签布局' + index); await mkdir(folder, { recursive: true });
      const name = index < 2 ? '同名.md' : '用于检查多文档标签横向滚动的长文件名称' + index + '.md';
      const target = path.join(folder, name); await writeFile(target, '# 标签文档 ' + index + '\n\n相同文件名仍属于不同路径。\n'); stressPaths.push(target);
    }
    await app.evaluate(({ dialog }, targets) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: targets }); }, stressPaths);
    await page.getByRole('button', { name: '打开', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('[role=tab]').length === 8);
    assert.equal(await page.getByRole('tab', { name: '同名.md', exact: true }).count(), 2, '不同文件夹同名文档不能合并');
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(720, 640));
    await page.waitForFunction(() => window.innerWidth === 720);
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    const barGeometry = await page.locator('#document-tabs').evaluate(bar => {
      const rect = bar.getBoundingClientRect(), active = bar.querySelector('[aria-selected=true]').getBoundingClientRect();
      return { overflow: bar.scrollWidth > bar.clientWidth, visible: active.left >= rect.left && active.right <= rect.right, bodyTop: document.querySelector('.workspace').getBoundingClientRect().top, bottom: rect.bottom };
    });
    assert.ok(barGeometry.overflow && barGeometry.visible && barGeometry.bodyTop >= barGeometry.bottom, '多标签窄窗口须可横向滚动且活动标签可见：' + JSON.stringify(barGeometry));
    await page.getByRole('tab', { name: '同名.md', exact: true }).nth(0).click();
    await page.waitForFunction(target => document.querySelector('#file-path').textContent === target, stressPaths[0]);
    assert.equal(await page.locator('.tiptap h1').textContent(), '标签文档 0');
    await page.getByRole('tab', { name: '同名.md', exact: true }).nth(1).click();
    await page.waitForFunction(target => document.querySelector('#file-path').textContent === target, stressPaths[1]);
    assert.equal(await page.locator('.tiptap h1').textContent(), '标签文档 1');
    await page.getByRole('tab', { name: '乙.md', exact: true }).click();
    for (let index = 0; index < stressPaths.length; index++) {
      await page.getByRole('button', { name: '关闭 ' + path.basename(stressPaths[index]), exact: true }).first().click();
      await page.waitForFunction(count => document.querySelectorAll('[role=tab]').length === count, 7 - index);
    }
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1180, 820));
    await page.waitForFunction(() => window.innerWidth === 1180);
    await page.locator('#toast').waitFor({ state: 'hidden' });
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    await page.screenshot({ path: process.env.MOYE_TABS_PREVIEW || path.join(testDir, 'tabs.png'), scale: 'css' });
    assert.deepEqual(errors, []);
    const savedSkill = path.join(testDir, '新模板.md');
    await app.evaluate(({ dialog }, target) => { dialog.showMessageBox = async () => ({ response: 0 }); dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }); }, savedSkill);
    const closed = page.waitForEvent('close');
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close()); await closed;
    assert.match(await readFile(savedSkill, 'utf8'), /new-template/);
    console.log('TABS PASS: independent positions, buffers, modes/undo; duplicate activation; invalid background metadata; cancel/save close; Save As collision; last-tab fallback; template/shortcuts; all-tab exit/save freeze; multiple Open, same filenames and overflow layout');
  } catch (error) {
    const page = await app.firstWindow().catch(() => null);
    if (page) console.error('TABS FAILURE STATE', await page.evaluate(async () => ({ name: document.querySelector('#document-name')?.textContent, toast: document.querySelector('#toast')?.textContent, skill: document.querySelector('#skill-name')?.value, tabs: [...document.querySelectorAll('[role=tab]')].map(node => node.textContent), snapshot: await window.moye.ready() })).catch(() => null));
    throw error;
  } finally {
    await app.evaluate(({ BrowserWindow }) => { for (const window of BrowserWindow.getAllWindows()) window.destroy(); }).catch(() => {});
    await app.close().catch(() => {});
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
