const { _electron: electron } = require('playwright');
const { writeFile, readFile, mkdir } = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const dir = path.resolve(__dirname, '../.desktop-test/mindmap-style-' + Date.now());
  await mkdir(dir, { recursive: true });
  const note = path.join(dir, '星标笔记.md'), file = path.join(dir, '节点外观.mdmap');
  await writeFile(note, '# 星标笔记\n\n从星星打开。\n');
  const node = (id, parent, text, linked = null) => ({ id, parent, text, file: linked, collapsed: false });
  await writeFile(file, JSON.stringify({ format: 'md-mindmap', version: 1, root: 'root', nodes: [node('root', null, '中心主题'), node('a', 'root', '有关联的节点', note), node('b', 'root', '普通节点')] }));
  const app = await electron.launch({ executablePath: process.env.MOYE_EXE || require('electron'), args: [...(process.env.MOYE_EXE ? [] : [path.resolve(__dirname, '..')]), file, '--user-data-dir=' + path.join(dir, 'profile')], timeout: 30000 });
  try {
    const page = await app.firstWindow(); page.setDefaultTimeout(8000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    const button = name => page.getByRole('button', { name, exact: true });
    const idle = () => page.waitForFunction(() => !document.querySelector('#save').disabled);
    const a = page.locator('[data-node-id="a"]'), b = page.locator('[data-node-id="b"]');
    await a.waitFor();
    assert.equal(await page.locator('.mindmap-no-file').count(), 0, '未关联节点不显示占位提示');
    assert.doesNotMatch(await page.locator('.mindmap-view').textContent(), /未关联/);
    const star = page.locator('[data-open-node="a"]');
    assert.equal(await star.textContent(), '★'); assert.match(await star.getAttribute('title'), /星标笔记\.md/);
    assert.equal(await page.locator('[data-node-card="root"] .mindmap-file').count(), 0);
    const picker = page.getByLabel('节点文字颜色', { exact: true });
    assert.ok(await picker.isDisabled(), '阅读模式禁止更改颜色');
    await button('编辑').click(); await idle(); await a.click();
    assert.ok(await picker.isVisible()); assert.ok(await button('默认颜色').isVisible());
    const titleColor = locator => locator.locator('.mindmap-node-title').evaluate(title => getComputedStyle(title).color);
    const automatic = await titleColor(a);
    // Exercise the renderer event emitted when the native color picker commits a selection.
    const chooseColor = value => picker.evaluate((input, color) => { input.value = color; input.dispatchEvent(new Event('change', { bubbles: true })); }, value);
    await chooseColor('#c03a59'); assert.equal(await titleColor(a), 'rgb(192, 58, 89)');
    await page.locator('.mindmap-canvas').focus(); await page.keyboard.press('Control+z'); assert.equal(await titleColor(a), automatic);
    await page.keyboard.press('Control+y'); assert.equal(await titleColor(a), 'rgb(192, 58, 89)');
    await button('默认颜色').click(); assert.equal(await titleColor(a), automatic);
    await page.keyboard.press('Control+z'); assert.equal(await titleColor(a), 'rgb(192, 58, 89)');
    const r = await a.boundingBox(); await page.mouse.move(r.x + 40, r.y + 20); await page.mouse.down(); await page.mouse.move(r.x - 40, r.y - 10, { steps: 8 }); await page.mouse.up();
    await a.click({ button: 'right' }); await page.locator('[data-action="connect"]').click(); await b.click();
    await button('保存').click(); await idle();
    let saved = JSON.parse(await readFile(file, 'utf8'));
    assert.equal(saved.version, 3, '拖动和连线不能把带颜色的图降级');
    assert.equal(saved.nodes[1].color, '#c03a59'); assert.equal(saved.connections.length, 1); assert.deepEqual(saved.nodes[1].offset, { x: -80, y: -30 });
    assert.equal(saved.nodes[1].file, '星标笔记.md');
    await a.click(); await button('取消关联').click(); assert.equal(await star.count(), 0); assert.doesNotMatch(await page.locator('.mindmap-view').textContent(), /未关联/);
    await page.keyboard.press('Control+z'); assert.equal(await star.textContent(), '★');
    await button('保存').click(); await idle();
    await star.click(); await idle(); assert.equal(await page.locator('#document-name').textContent(), '星标笔记.md');
    await page.getByRole('tab', { name: '节点外观.mdmap', exact: true }).click(); await idle();
    await button('关闭 节点外观.mdmap').click(); await idle();
    await app.evaluate(({ dialog }, target) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [target] }); }, file);
    await button('打开').click(); await idle(); assert.equal(await titleColor(a), 'rgb(192, 58, 89)'); assert.equal(await star.textContent(), '★');
    assert.ok(await picker.isDisabled()); await button('编辑').click(); await idle(); await b.click();
    const light = await titleColor(b);
    await page.locator('#more-toggle').click(); await page.locator('#theme').click();
    assert.notEqual(await titleColor(b), light, '默认颜色跟随外观'); assert.equal(await titleColor(a), 'rgb(192, 58, 89)', '自定义颜色保持');
    const themeHex = await b.locator('.mindmap-node-title').evaluate(title => '#' + getComputedStyle(title).color.match(/\d+/g).slice(0, 3).map(value => Number(value).toString(16).padStart(2, '0')).join(''));
    assert.equal(await picker.inputValue(), themeHex, '切换外观时，默认颜色色块也应立即同步');
    await a.click(); await button('默认颜色').click(); assert.equal(await titleColor(a), await titleColor(b));
    await button('保存').click(); await idle(); saved = JSON.parse(await readFile(file, 'utf8')); assert.equal(Object.hasOwn(saved.nodes[1], 'color'), false);
    await chooseColor('#60a5fa'); await button('保存').click(); await idle();
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(720, 640)); await page.waitForFunction(() => innerWidth === 720);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 720);
    for (const control of [picker, button('默认颜色')]) assert.ok(await control.evaluate(element => { const r = element.getBoundingClientRect(); return r.width > 0 && r.left >= 0 && r.right <= innerWidth; }), '窄窗口颜色操作保持可见');
    await page.screenshot({ path: path.resolve(__dirname, '../.desktop-test/MD节点颜色窄屏预览-0.1.16.png') });
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1180, 780)); await page.waitForFunction(() => innerWidth === 1180);
    await button('居中').click(); await page.screenshot({ path: path.resolve(__dirname, '../.desktop-test/MD节点颜色预览-0.1.16.png') });
    assert.deepEqual(errors, []);
    console.log('MINDMAP STYLE PASS: color, default, undo/redo, v3 after drag/connect, save/reopen, star open/unlink, no unlinked hints, theme and narrow controls. Native picker commit event is simulated.');
  } finally { await app.evaluate(({ BrowserWindow }) => { for (const window of BrowserWindow.getAllWindows()) window.destroy(); }).catch(() => {}); await app.close().catch(() => {}); }
})().catch(error => { console.error(error); process.exitCode = 1; });
