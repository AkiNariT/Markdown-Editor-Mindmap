const { _electron: electron } = require('playwright');
const { writeFile, readFile, mkdir, readdir, symlink } = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const testDir = path.resolve(__dirname, '../.desktop-test/naming-' + Date.now()); await mkdir(testDir, { recursive: true });
  const original = '# 原始文档\n\n正文。\n\n![图片](image.png)\n\n' + Array.from({ length: 35 }, (_, i) => `## 第${i + 1}节\n\n正文${i + 1}。\n\n`).join('');
  const file = path.join(testDir, '原名.md'), renamed = path.join(testDir, '新文件名.md'), other = path.join(testDir, '已打开.md');
  await writeFile(file, original); await writeFile(other, '# 其他文件\n');
  await writeFile(path.join(testDir, '磁盘已有.md'), '磁盘原文');
  await writeFile(path.join(testDir, 'image.png'), Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j9AAAAABJRU5ErkJggg==', 'base64'));
  const executablePath = process.env.MOYE_EXE || require('electron');
  const args = process.env.MOYE_EXE ? [file, other] : [path.resolve(__dirname, '..'), file, other];
  const app = await electron.launch({ executablePath, args: [...args, '--user-data-dir=' + path.join(testDir, 'profile-' + process.pid + '-' + Date.now())], timeout: 30000 });
  try {
    const page = await app.firstWindow(); page.setDefaultTimeout(8000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.waitForSelector('.tiptap h1');
    assert.equal(await page.locator('#rename').count(), 1, '顶部必须有直接命名入口');
    const submitName = async name => {
      await page.locator('#rename').click(); await page.locator('#filename').fill(name); await page.locator('#name-confirm').click();
      await page.waitForFunction(() => !document.querySelector('#name-confirm').disabled);
    };
    await page.locator('#new').click();
    await submitName('我的草稿');
    assert.equal(await page.locator('#document-name').textContent(), '我的草稿.md');
    assert.equal(await page.getByRole('tab', { name: '我的草稿.md', exact: true }).count(), 1);
    await app.evaluate(({ dialog }) => { globalThis.nameDialogs = []; dialog.showMessageBox = async (_, options) => { globalThis.nameDialogs.push(options.message); return { response: 2 }; }; });
    await page.getByRole('button', { name: '关闭 我的草稿.md', exact: true }).click();
    assert.equal(await page.getByRole('tab', { name: '我的草稿.md', exact: true }).count(), 1, '仅命名的空草稿关闭时也应提醒保存');
    await page.keyboard.press('F2'); await page.locator('#filename').fill('取消的新名'); await page.keyboard.press('Escape');
    assert.equal(await page.locator('#document-name').textContent(), '我的草稿.md');
    await page.getByRole('button', { name: '对照', exact: true }).click();
    const input = page.locator('.source-input'); await input.fill('# 草稿标题\n\n草稿正文。\n');
    const draft = path.join(testDir, '我的草稿.md');
    await app.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async (_, options) => { globalThis.defaultName = options.defaultPath; return { canceled: false, filePath: target }; }; }, draft);
    await page.locator('#save').click(); await page.waitForFunction(() => document.querySelector('#dirty-dot').hidden);
    assert.equal(await app.evaluate(() => globalThis.defaultName), '我的草稿.md');
    assert.equal(await readFile(draft, 'utf8'), '# 草稿标题\n\n草稿正文。\n');
    await page.getByRole('tab', { name: '原名.md', exact: true }).click();
    await page.getByRole('button', { name: '对照', exact: true }).click(); await page.getByRole('button', { name: '编辑', exact: true }).click();
    await input.focus(); await page.keyboard.press('Control+End'); await page.keyboard.insertText('未保存尾部');
    await page.locator('#sync-scroll').uncheck(); await page.keyboard.press('Control+=');
    await input.evaluate(node => { node.scrollTop = 750; });
    await page.locator('.canvas').evaluate(node => node.scrollTo({ top: 1100, behavior: 'instant' }));
    const snapshot = await page.evaluate(() => ({ text: document.querySelector('.source-input').value, top: document.querySelector('.source-input').scrollTop, preview: document.querySelector('.canvas').scrollTop, selection: document.querySelector('.source-input').selectionStart }));
    await submitName('新文件名');
    assert.equal(await page.locator('#document-name').textContent(), '新文件名.md');
    assert.equal(await input.inputValue(), snapshot.text);
    assert.equal(await page.locator('#dirty-dot').isVisible(), true);
    assert.equal(await page.locator('#zoom-reset').textContent(), '110%');
    assert.ok(Math.abs(await input.evaluate(node => node.scrollTop) - snapshot.top) < 2);
    assert.ok(Math.abs(await page.locator('.canvas').evaluate(node => node.scrollTop) - snapshot.preview) < 2);
    assert.equal(await input.evaluate(node => node.selectionStart), snapshot.selection);
    assert.equal(await readFile(renamed, 'utf8'), original, '改名不能顺带保存未保存正文');
    assert.ok(!(await readdir(testDir)).includes('原名.md'));
    await page.waitForFunction(() => document.querySelector('.tiptap img')?.naturalWidth === 1);
    await input.focus(); await page.keyboard.press('Control+z'); assert.equal(await input.inputValue(), original, '重命名后仍保留源码撤销历史');
    await page.keyboard.press('Control+Shift+z'); assert.equal(await input.inputValue(), snapshot.text);
    for (const name of ['../非法', 'NUL.md', '磁盘已有.md', '已打开.md']) {
      await submitName(name); assert.equal(await page.locator('#name-dialog').isVisible(), true);
      assert.ok((await page.locator('#name-error').textContent()).length > 0);
      assert.equal(await page.locator('#document-name').textContent(), '新文件名.md');
      await page.keyboard.press('Escape');
    }
    assert.equal(await readFile(path.join(testDir, '磁盘已有.md'), 'utf8'), '磁盘原文');
    await page.locator('#save').click(); await page.waitForFunction(() => document.querySelector('#dirty-dot').hidden);
    assert.equal(await readFile(renamed, 'utf8'), snapshot.text, '保存使用新路径');
    await page.getByRole('tab', { name: '已打开.md', exact: true }).click();
    await app.evaluate(({ dialog }, target) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [target] }); }, renamed);
    await page.locator('#open').click(); await page.waitForFunction(() => document.querySelector('#document-name').textContent === '新文件名.md');
    assert.equal(await page.locator('[role=tab]').count(), 3, '重复打开改名后的文件仍复用原标签');
    const realDir = path.join(testDir, 'real-files'), aliasDir = path.join(testDir, 'alias-files');
    await mkdir(realDir); await symlink(realDir, aliasDir, 'junction');
    await writeFile(path.join(realDir, '别名文件.md'), '# 目录别名\n');
    await app.evaluate(({ dialog }, target) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [target] }); }, path.join(aliasDir, '别名文件.md'));
    await page.locator('#open').click(); await page.waitForFunction(() => document.querySelector('#document-name').textContent === '别名文件.md');
    await submitName('别名改名');
    await app.evaluate(({ dialog }, target) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [target] }); }, path.join(realDir, '别名改名.md'));
    await page.locator('#open').click(); await page.waitForFunction(() => document.querySelector('#document-name').textContent === '别名改名.md');
    assert.equal(await page.locator('[role=tab]').count(), 4, '从目录别名改名后，通过真实路径打开也应复用同一标签');
    await page.locator('#new').click(); await page.getByRole('button', { name: '源码', exact: true }).click();
    await input.fill('---\nname: naming-skill\ndescription: 测试命名。\n---\n\n# 技能\n');
    await submitName('SKILL.md'); await page.getByRole('button', { name: '对照', exact: true }).click();
    assert.equal(await page.locator('#skill-name').inputValue(), 'naming-skill', '命名为SKILL.md后显示技能字段');
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(720, 640));
    assert.ok(await page.locator('#rename').isVisible());
    await page.keyboard.press('F2'); await page.locator('#filename').fill('窄窗口名称');
    assert.ok(await page.locator('#name-dialog').evaluate(node => { const r=node.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && r.top >= 0 && r.bottom <= innerHeight; }), '窄窗口命名框应完整显示');
    await page.keyboard.press('Enter'); await page.waitForFunction(() => !document.querySelector('#name-dialog').open);
    assert.equal(await page.locator('#document-name').textContent(), '窄窗口名称.md');
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth === innerWidth));
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1180, 780));
    await page.keyboard.press('F2'); await page.locator('#filename').fill('我的项目笔记.md');
    await page.waitForFunction(() => innerWidth === 1180);
    await page.screenshot({ path: path.resolve(__dirname, '../.desktop-test/MD文件命名预览.png'), fullPage: true });
    assert.deepEqual(errors, []);
    console.log('NAMING PASS: visible name/F2, drafts before save, empty named draft close guard, cancel/Enter, save default, disk rename without saving buffer, history/position/zoom/images, conflicts, duplicate tabs, SKILL and narrow layout');
  } finally {
    await app.evaluate(({ BrowserWindow }) => { for (const window of BrowserWindow.getAllWindows()) window.destroy(); }).catch(() => {});
    await app.close().catch(() => {});
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
